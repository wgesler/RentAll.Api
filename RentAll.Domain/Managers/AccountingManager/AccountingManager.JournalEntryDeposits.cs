    private async Task<AccountingJournalEntryResult> CreateJournalEntryFromDepositWithResultAsync(Deposit deposit, Guid currentUser)
    {
        var trail = new AccountingSyncBailTrail();
        var result = await CreateJournalEntryFromDepositWithDiagnosticsAsync(deposit, currentUser, trail);
        if (result.HasWarning || result.JournalEntry == null)
        {
            // Day-to-day create: surface silent exits that Sync will also log as DepositSkip.
            if (result.JournalEntry == null && !result.HasWarning)
                return AccountingJournalEntryResult.WarningResult(trail.FormatBailTrail());
        }

        return result;
    }

    private async Task<AccountingJournalEntryResult> CreateJournalEntryFromDepositWithDiagnosticsAsync(
        Deposit deposit,
        Guid currentUser,
        AccountingSyncBailTrail trail)
    {
        var depositLabel = string.IsNullOrWhiteSpace(deposit.DepositCode)
            ? deposit.DepositId.ToString()
            : deposit.DepositCode.Trim();
        trail.Note($"Deposit {depositLabel} IsActive={deposit.IsActive} Amount={deposit.Amount:0.00} Splits={deposit.Splits?.Count ?? 0} BankAccountId={deposit.BankAccountId}");

        if (!await IsAccountingFeatureEnabledAsync(deposit.OrganizationId))
        {
            trail.Bail("Exit: accounting feature is disabled for organization.");
            return AccountingJournalEntryResult.WarningResult("Accounting feature is disabled for organization.");
        }

        if (!ShouldCreateJournalEntryForDeposit(deposit))
        {
            AppendDepositShouldCreateBailReasons(deposit, trail);
            trail.Bail("Exit: ShouldCreateJournalEntryForDeposit=false.");
            return AccountingJournalEntryResult.WarningResult(trail.FormatBailTrail());
        }

        try
        {
            ValidateDepositForJournalEntry(deposit);

            await EnrichDepositSplitsFromJournalEntryLinesAsync(deposit);
            ApplyDepositHeaderContextFromSplits(deposit);
            trail.Note($"After enrich: splits={deposit.Splits?.Count ?? 0}");

            var journalEntry = BuildJournalEntryFromDepositRecord(deposit, currentUser);
            trail.Note($"Built deposit JE lines={journalEntry.JournalEntryLines?.Count ?? 0}");

            var created = await CreateAutoGeneratedJournalEntryAsync(journalEntry);
            if (created == null)
            {
                trail.Bail("Exit: CreateAutoGeneratedJournalEntryAsync returned null (feature off or rejected).");
                return AccountingJournalEntryResult.WarningResult(trail.FormatBailTrail());
            }

            trail.Note($"Created {created.JournalEntryCode} kind={(int)created.JournalEntryKindId} DepositId={created.DepositId}");
            await SyncDepositDocumentLinksAsync(deposit, currentUser);
            trail.Note("SyncDepositDocumentLinksAsync completed.");

            return AccountingJournalEntryResult.Success(created);
        }
        catch (Exception ex)
        {
            trail.Bail($"Exception: {ex.Message}");
            await LogAccountingErrorAsync(
                trigger: "Deposit",
                organizationId: deposit.OrganizationId,
                officeId: deposit.OfficeId,
                sourceTypeId: (int)SourceType.Deposit,
                sourceId: deposit.DepositId,
                documentCode: depositLabel,
                accountingPeriod: deposit.AccountingPeriod == default ? null : deposit.AccountingPeriod,
                amount: deposit.Amount,
                message: ex.Message + Environment.NewLine + "Bail trail:" + Environment.NewLine + trail.FormatBailTrail(),
                currentUser: currentUser);
            return AccountingJournalEntryResult.WarningResult(ex.Message);
        }
    }

