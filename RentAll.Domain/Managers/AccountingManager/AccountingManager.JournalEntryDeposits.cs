    #region Document Link
    private static void ApplyDepositDocumentLink(JournalEntry journalEntry, Deposit deposit)
    {
        if (deposit.DepositId == Guid.Empty)
            return;

        journalEntry.DepositId = deposit.DepositId;
        journalEntry.DepositCode = deposit.DepositCode.Trim();
    }

    private static void ClearDepositDocumentLink(JournalEntry journalEntry)
    {
        journalEntry.DepositId = null;
        journalEntry.DepositCode = null;
    }

    private async Task SyncDepositDocumentLinksAsync(Deposit deposit, Guid currentUser)
    {
        if (deposit.DepositId == Guid.Empty || !deposit.IsActive)
            return;

        if (!await IsAccountingFeatureEnabledAsync(deposit.OrganizationId))
            return;

        await ClearDepositDocumentLinksAsync(deposit.OrganizationId, deposit.DepositId, currentUser);

        await ApplyDepositDocumentLinksFromDepositSplitsAsync(deposit, currentUser);

        var paymentIds = await CollectPaymentIdsFromDepositSplitsAsync(deposit);
        foreach (var paymentId in paymentIds)
        {
            var paymentJournalEntries = (await _journalEntryRepository.GetJournalEntriesByPaymentIdAsync(new JournalEntryGetByPaymentIdCriteria
            {
                OrganizationId = deposit.OrganizationId,
                PaymentId = paymentId
            })).ToList();

            foreach (var journalEntry in paymentJournalEntries)
            {
                ApplyDepositDocumentLink(journalEntry, deposit);
                journalEntry.ModifiedBy = currentUser;
                await UpdateJournalEntryWithoutRetainedEarningsRefreshAsync(journalEntry, requireActiveLines: true);
            }
        }

        var depositJournalEntries = (await _journalEntryRepository.GetJournalEntriesAsync(new JournalEntryGetCriteria
        {
            OrganizationId = deposit.OrganizationId,
            OfficeIds = deposit.OfficeId.ToString(),
            SourceTypeId = (int)SourceType.Deposit,
            SourceId = deposit.DepositId,
            IncludeUnposted = true
        })).ToList();

        foreach (var depositJournalEntry in depositJournalEntries)
        {
            ApplyDepositDocumentLink(depositJournalEntry, deposit);
            depositJournalEntry.ModifiedBy = currentUser;
            await UpdateJournalEntryWithoutRetainedEarningsRefreshAsync(depositJournalEntry, requireActiveLines: true);
        }
    }

    private async Task ClearDepositDocumentLinksAsync(Guid organizationId, Guid depositId, Guid currentUser)
    {
        if (depositId == Guid.Empty)
            return;

        var linkedEntries = (await _journalEntryRepository.GetJournalEntriesByDepositIdAsync(new JournalEntryGetByDepositIdCriteria
        {
            OrganizationId = organizationId,
            DepositId = depositId
        })).ToList();

        foreach (var journalEntry in linkedEntries)
        {
            ClearDepositDocumentLink(journalEntry);
            journalEntry.ModifiedBy = currentUser;
            await UpdateJournalEntryWithoutRetainedEarningsRefreshAsync(journalEntry, requireActiveLines: true);
        }
    }

    private async Task<HashSet<Guid>> CollectPaymentIdsFromDepositSplitsAsync(Deposit deposit)
    {
        var paymentIds = new HashSet<Guid>();

        foreach (var split in deposit.Splits ?? [])
        {
            if (split.JournalEntryLineId is not { } journalEntryLineId || journalEntryLineId == Guid.Empty)
                continue;

            var sourceLine = await _journalEntryRepository.GetJournalEntryLineByIdAsync(journalEntryLineId);
            if (sourceLine == null || sourceLine.JournalEntryId == Guid.Empty)
                continue;

            var undepositedFundsJournalEntry = await _journalEntryRepository.GetJournalEntryByIdAsync(
                sourceLine.JournalEntryId,
                deposit.OrganizationId);
            if (undepositedFundsJournalEntry?.PaymentId is { } paymentId && paymentId != Guid.Empty)
                paymentIds.Add(paymentId);
        }

        return paymentIds;
    }

    private async Task ApplyDepositDocumentLinksFromDepositSplitsAsync(Deposit deposit, Guid currentUser)
    {
        var processedJournalEntryIds = new HashSet<Guid>();

        foreach (var split in deposit.Splits ?? [])
        {
            if (split.JournalEntryLineId is not { } journalEntryLineId || journalEntryLineId == Guid.Empty)
                continue;

            var sourceLine = await _journalEntryRepository.GetJournalEntryLineByIdAsync(journalEntryLineId);
            if (sourceLine?.JournalEntryId is not { } journalEntryId || journalEntryId == Guid.Empty)
                continue;

            if (!processedJournalEntryIds.Add(journalEntryId))
                continue;

            var journalEntry = await _journalEntryRepository.GetJournalEntryByIdAsync(journalEntryId, deposit.OrganizationId);
            if (journalEntry == null)
                continue;

            ApplyDepositDocumentLink(journalEntry, deposit);
            await TryApplyPaymentDocumentLinkFromDepositedJournalEntryAsync(journalEntry);
            journalEntry.ModifiedBy = currentUser;
            await UpdateJournalEntryWithoutRetainedEarningsRefreshAsync(journalEntry, requireActiveLines: true);
        }
    }

    private async Task TryApplyPaymentDocumentLinkFromDepositedJournalEntryAsync(JournalEntry journalEntry)
    {
        if (journalEntry.PaymentId is { } existingPaymentId && existingPaymentId != Guid.Empty)
            return;

        if (!string.IsNullOrWhiteSpace(journalEntry.PaymentCode))
            return;

        if (journalEntry.SourceTypeId != (int)SourceType.Invoice
            || journalEntry.SourceId is not { } invoiceId
            || invoiceId == Guid.Empty)
        {
            return;
        }

        var invoice = await _accountingRepository.GetInvoiceByIdAsync(invoiceId, journalEntry.OrganizationId);
        if (invoice == null)
            return;

        var costCodeById = await LoadCostCodeByOfficeIdAsync(journalEntry.OrganizationId, journalEntry.OfficeId);
        foreach (var ledgerLine in invoice.LedgerLines.Where(line => line.Amount != 0))
        {
            if (!costCodeById.TryGetValue(ledgerLine.CostCodeId, out var costCode) || !IsPaymentLedgerLine(costCode))
                continue;

            if (!MatchesInvoicePaymentLedgerLineMemo(journalEntry, invoice, ledgerLine))
                continue;

            if (ledgerLine.PaymentId is not { } paymentId || paymentId == Guid.Empty)
                continue;

            await ApplyPaymentDocumentLinkAsync(journalEntry, ledgerLine, journalEntry.OrganizationId);
            return;
        }
    }
