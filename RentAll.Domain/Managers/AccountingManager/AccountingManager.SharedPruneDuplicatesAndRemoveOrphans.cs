using RentAll.Domain.Enums;
using RentAll.Domain.Models;

namespace RentAll.Domain.Managers;

public partial class AccountingManager
{
    #region Shared Prune Duplicates And Remove Orphans
    private async Task PruneOpenDuplicateAutoGeneratedJournalEntriesAsync(List<JournalEntry> entries, Guid organizationId, Guid currentUser)
    {
        if (entries.Count <= 1)
            return;

        SortJournalEntriesForDuplicateRetention(entries);
        var retained = entries[0];

        while (entries.Count > 1)
        {
            var duplicate = entries[^1];
            if (duplicate.PostingStatusId == PostingStatus.Open)
            {
                if (currentUser != Guid.Empty)
                    await ReconnectDuplicateJournalEntryLinksAsync(retained, duplicate, organizationId, currentUser);

                await DeleteOpenJournalEntryAsync(duplicate.JournalEntryId, organizationId);
            }

            entries.RemoveAt(entries.Count - 1);
        }
    }

    private async Task RemoveOrphanOpenAutoGeneratedJournalEntriesAsync(IEnumerable<JournalEntry> entries, IReadOnlyCollection<Guid> retainJournalEntryIds, Guid organizationId, Guid currentUser)
    {
        var entryList = entries.ToList();
        var retainedEntries = entryList
            .Where(entry => retainJournalEntryIds.Contains(entry.JournalEntryId))
            .ToList();

        foreach (var entry in entryList)
        {
            if (retainJournalEntryIds.Contains(entry.JournalEntryId))
                continue;

            if (entry.PostingStatusId != PostingStatus.Open)
                continue;

            var retained = retainedEntries.FirstOrDefault(candidate => candidate.JournalEntryKindId == entry.JournalEntryKindId)
                ?? retainedEntries.FirstOrDefault();

            if (retained != null && currentUser != Guid.Empty)
                await ReconnectDuplicateJournalEntryLinksAsync(retained, entry, organizationId, currentUser);

            await DeleteOpenJournalEntryAsync(entry.JournalEntryId, organizationId);
        }
    }
    #endregion
}
