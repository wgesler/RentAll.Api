    private async Task<JournalEntry?> BuildJournalEntryFromPaymentForSecurityDepositActualAsync(Invoice invoice, LedgerLine paymentLedgerLine, decimal paymentAmount, DateOnly transactionDate, Guid currentUser, Invoice? paymentSourceInvoice = null)
    {
        var allocationInvoice = await ResolveInvoiceForOwnerShareAsync(invoice);
        var costCodeById = await LoadCostCodeByOfficeIdAsync(allocationInvoice.OrganizationId, allocationInvoice.OfficeId);
        if (!TryGetInvoiceLedgerLineByTransactionType(allocationInvoice, TransactionType.SecurityDeposit, costCodeById, out var securityDepositLine))
            return null;

        var appliedAmount = await CalculateSecurityDepositAppliedForInvoicePaymentAsync(allocationInvoice, paymentSourceInvoice ?? invoice, paymentLedgerLine, paymentAmount, costCodeById);
        if (!appliedAmount.HasValue || appliedAmount.Value == 0)
            return null;

        var (chartOfAccounts, accountingOffice) = await LoadAccountContextAsync(invoice.OrganizationId, invoice.OfficeId);
        var lineContext = await ResolveInvoiceJournalEntryLineContextAsync(invoice, securityDepositLine);
        var memo = BuildSecurityDepositActualMemo(invoice, securityDepositLine, paymentLedgerLine);
        var journalEntryLines = BuildJournalEntryLinesForSecurityDepositActual(
            invoice,
            securityDepositLine,
            appliedAmount.Value,
            chartOfAccounts,
            accountingOffice,
            costCodeById,
            lineContext,
            memo,
            currentUser);
        if (journalEntryLines.Count == 0)
            return null;

        var journalEntry = ClassifyJournalEntry(new JournalEntry
        {
            OrganizationId = invoice.OrganizationId,
            OfficeId = invoice.OfficeId,
            TransactionDate = transactionDate,
            AccountingPeriod = invoice.AccountingPeriod != default
                ? invoice.AccountingPeriod
                : FirstDayOfMonth(transactionDate),
            SourceTypeId = (int)SourceType.Invoice,
            SourceId = invoice.InvoiceId,
            SourceCode = ResolveJournalEntrySourceCodeFromInvoice(invoice),
            Memo = memo,
            IsCashOnly = true,
            JournalEntryLines = journalEntryLines,
            CreatedBy = currentUser
        }, JournalEntryKind.SecurityDepositActual, Perspective.Company);

        await ApplyPaymentDocumentLinkAsync(journalEntry, paymentLedgerLine, invoice.OrganizationId);
        return journalEntry;
    }

