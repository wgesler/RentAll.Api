    private async Task<decimal?> CalculateFeesAppliedForInvoicePaymentAsync(Invoice waterfallInvoice, LedgerLine paymentLedgerLine, IReadOnlyDictionary<int, CostCode> costCodeById, IReadOnlyList<JournalEntry>? workingEntries = null)
    {
        if (paymentLedgerLine.LedgerLineId == Guid.Empty)
            return null;

        var orderedPayments = GetOrderedInvoicePaymentLines(waterfallInvoice, costCodeById);
        if (orderedPayments.All(payment => payment.LedgerLineId != paymentLedgerLine.LedgerLineId))
            orderedPayments = [.. orderedPayments, paymentLedgerLine];

        if (orderedPayments.Count == 0)
            return null;

        var securityDepositDue = await GetInvoiceSecurityDepositBaseAsync(waterfallInvoice);
        var sdwDue = await GetInvoiceSecurityDepositWaiverBaseAsync(waterfallInvoice);
        var rentDue = await GetInvoiceRentPlus4000BaseAsync(waterfallInvoice);
        var feesDue = await GetInvoiceFeesBaseAsync(waterfallInvoice);
        if (feesDue == 0)
            return null;

        var cumulativeFeesApplied = CalculateCumulativeFeesPaidThroughWaterfall(
            securityDepositDue,
            rentDue,
            sdwDue,
            feesDue,
            orderedPayments,
            paymentLedgerLine.LedgerLineId);
        if (cumulativeFeesApplied <= 0)
            return null;

        var priorFeesActual = await SumPriorFeesActualAmountAsync(waterfallInvoice, paymentLedgerLine, workingEntries);
        var incrementalFeesActual = RoundCurrency(cumulativeFeesApplied - priorFeesActual);
        return incrementalFeesActual > 0 ? incrementalFeesActual : null;
    }

    private async Task<decimal> SumPriorFeesActualAmountAsync(Invoice invoice, LedgerLine currentPaymentLedgerLine, IReadOnlyList<JournalEntry>? workingEntries)
    {
        var (chartOfAccounts, accountingOffice) = await LoadAccountContextAsync(invoice.OrganizationId, invoice.OfficeId);
        var escrowDepositAccountId = GetDefaultEscrowDepositAccount(chartOfAccounts, invoice.OfficeId, accountingOffice);

        var dbEntries = (await _journalEntryRepository.GetJournalEntriesAsync(new JournalEntryGetCriteria
        {
            OrganizationId = invoice.OrganizationId,
            OfficeIds = invoice.OfficeId.ToString(),
            SourceTypeId = (int)SourceType.Invoice,
            SourceId = invoice.InvoiceId,
            IncludeUnposted = true
        })).ToList();

        var entries = (workingEntries ?? [])
            .Where(entry => entry.JournalEntryKindId == JournalEntryKind.FeesActual && entry.SourceId == invoice.InvoiceId)
            .Concat(dbEntries.Where(entry => entry.JournalEntryKindId == JournalEntryKind.FeesActual))
            .GroupBy(entry => entry.JournalEntryId)
            .Select(group => group.First())
            .ToList();

        return entries.Sum(entry => entry.JournalEntryLines
            .Where(line => line.ChartOfAccountId == escrowDepositAccountId)
            .Sum(line => line.Credit - line.Debit));
    }

    private static decimal CalculateCumulativeFeesPaidThroughWaterfall(decimal securityDepositDue, decimal rentDue, decimal sdwDue, decimal feesDue, IReadOnlyList<LedgerLine> orderedPayments, Guid throughPaymentLedgerLineId)
    {
        var securityDepositRemaining = securityDepositDue;
        var rentRemaining = rentDue;
        var sdwRemaining = sdwDue;
        var feesRemaining = feesDue;
        var cumulativeFeesApplied = 0m;

        foreach (var payment in orderedPayments)
        {
            var paymentRemaining = payment.Amount;

            var applySecurityDeposit = Math.Min(Math.Max(paymentRemaining, 0m), securityDepositRemaining);
            securityDepositRemaining -= applySecurityDeposit;
            paymentRemaining -= applySecurityDeposit;

            var applyRent = Math.Min(Math.Max(paymentRemaining, 0m), rentRemaining);
            rentRemaining -= applyRent;
            paymentRemaining -= applyRent;

            var applySdw = Math.Min(Math.Max(paymentRemaining, 0m), sdwRemaining);
            sdwRemaining -= applySdw;
            paymentRemaining -= applySdw;

            var applyFees = Math.Min(Math.Max(paymentRemaining, 0m), feesRemaining);
            feesRemaining -= applyFees;
            cumulativeFeesApplied += applyFees;

            if (payment.LedgerLineId == throughPaymentLedgerLineId)
                break;
        }

        return RoundCurrency(cumulativeFeesApplied);
    }

    private async Task<PaymentWaterfallApplication> CalculatePaymentWaterfallApplicationForInvoicePaymentAsync(Invoice allocationInvoice, Invoice paymentSourceInvoice, LedgerLine paymentLedgerLine, decimal paymentAmount, IReadOnlyDictionary<int, CostCode> costCodeById)
    {
        if (paymentAmount == 0 || paymentLedgerLine.LedgerLineId == Guid.Empty)
            return PaymentWaterfallApplication.Zero;

        var securityDepositDue = await GetInvoiceSecurityDepositBaseAsync(allocationInvoice);
        var sdwDue = await GetInvoiceSecurityDepositWaiverBaseAsync(allocationInvoice);
        var rentDue = await GetInvoiceRentPlus4000BaseAsync(allocationInvoice);
        var feesDue = await GetInvoiceFeesBaseAsync(allocationInvoice);
        var orderedPayments = await ResolveOrderedPaymentsForOwnerActualAsync(
            allocationInvoice,
            paymentSourceInvoice,
            paymentLedgerLine,
            paymentAmount,
            costCodeById);
        if (orderedPayments.Count == 0)
            return PaymentWaterfallApplication.Zero;

        return CalculatePaymentWaterfallApplicationForLedgerLine(
            securityDepositDue,
            rentDue,
            sdwDue,
            feesDue,
            orderedPayments,
            paymentLedgerLine.LedgerLineId);
    }

    private static PaymentWaterfallApplication CalculatePaymentWaterfallApplicationForLedgerLine(decimal securityDepositDue, decimal rentDue, decimal sdwDue, decimal feesDue, IReadOnlyList<LedgerLine> orderedPayments, Guid paymentLedgerLineId)
    {
        var securityDepositRemaining = securityDepositDue;
        var rentRemaining = rentDue;
        var sdwRemaining = sdwDue;
        var feesRemaining = feesDue;

        foreach (var payment in orderedPayments)
        {
            var paymentRemaining = payment.Amount;

            var applySecurityDeposit = Math.Min(Math.Max(paymentRemaining, 0m), securityDepositRemaining);
            securityDepositRemaining -= applySecurityDeposit;
            paymentRemaining -= applySecurityDeposit;

            var applyRent = Math.Min(Math.Max(paymentRemaining, 0m), rentRemaining);
            rentRemaining -= applyRent;
            paymentRemaining -= applyRent;

            var applySdw = Math.Min(Math.Max(paymentRemaining, 0m), sdwRemaining);
            sdwRemaining -= applySdw;
            paymentRemaining -= applySdw;

            var applyFees = Math.Min(Math.Max(paymentRemaining, 0m), feesRemaining);
            feesRemaining -= applyFees;

            if (payment.LedgerLineId == paymentLedgerLineId)
            {
                return new PaymentWaterfallApplication(
                    RoundCurrency(applySecurityDeposit),
                    RoundCurrency(applyRent),
                    RoundCurrency(applySdw),
                    RoundCurrency(applyFees));
            }
        }

        return PaymentWaterfallApplication.Zero;
    }

    private static bool TryGetInvoiceLedgerLineByTransactionType(Invoice invoice, TransactionType transactionType, IReadOnlyDictionary<int, CostCode> costCodeById, out LedgerLine ledgerLine)
    {
        ledgerLine = null!;
        var match = invoice.LedgerLines
            .Where(line => line.Amount != 0)
            .FirstOrDefault(line =>
            {
                costCodeById.TryGetValue(line.CostCodeId, out var costCode);
                return costCode?.TransactionType == transactionType;
            });

        if (match == null)
            return false;

        ledgerLine = match;
        return true;
    }

