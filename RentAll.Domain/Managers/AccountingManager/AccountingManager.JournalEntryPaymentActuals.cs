    private async Task<decimal?> CalculateSecurityDepositAppliedForInvoicePaymentAsync(Invoice allocationInvoice, Invoice paymentSourceInvoice, LedgerLine paymentLedgerLine, decimal paymentAmount, IReadOnlyDictionary<int, CostCode> costCodeById)
    {
        var application = await CalculatePaymentWaterfallApplicationForInvoicePaymentAsync(allocationInvoice, paymentSourceInvoice, paymentLedgerLine, paymentAmount, costCodeById);
        return application.SecurityDepositApplied == 0 ? null : application.SecurityDepositApplied;
    }

