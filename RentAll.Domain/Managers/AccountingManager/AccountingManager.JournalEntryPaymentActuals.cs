    private List<JournalEntryLine> BuildJournalEntryLinesForSecurityDepositActual(Invoice invoice, LedgerLine securityDepositLine, decimal actualAmount, List<ChartOfAccount> chartOfAccounts, AccountingOffice? accountingOffice, IReadOnlyDictionary<int, CostCode> costCodeById, JournalEntryLineContext lineContext, string memo, Guid currentUser)
    {
        costCodeById.TryGetValue(securityDepositLine.CostCodeId, out var costCode);
        var tenantIncomeAccountId = GetDefaultTenantIncome(chartOfAccounts, invoice.OfficeId, accountingOffice, costCode);
        var escrowSecurityDepositAccountId = GetDefaultEscrowSecurityDepositAccount(chartOfAccounts, invoice.OfficeId, accountingOffice);
        if (tenantIncomeAccountId <= 0 || escrowSecurityDepositAccountId <= 0)
            return [];

        var tenantIncomeLine = new JournalEntryLine
        {
            ChartOfAccountId = tenantIncomeAccountId,
            CostCodeId = securityDepositLine.CostCodeId,
            Debit = actualAmount > 0 ? actualAmount : 0,
            Credit = actualAmount < 0 ? Math.Abs(actualAmount) : 0,
            Memo = memo,
            CreatedBy = currentUser
        };
        ApplyJournalEntryLineContext(tenantIncomeLine, lineContext);

        var escrowLine = new JournalEntryLine
        {
            ChartOfAccountId = escrowSecurityDepositAccountId,
            CostCodeId = securityDepositLine.CostCodeId,
            Debit = actualAmount < 0 ? Math.Abs(actualAmount) : 0,
            Credit = actualAmount > 0 ? actualAmount : 0,
            Memo = memo,
            CreatedBy = currentUser
        };
        ApplyJournalEntryLineContext(escrowLine, lineContext);

        return [tenantIncomeLine, escrowLine];
    }

