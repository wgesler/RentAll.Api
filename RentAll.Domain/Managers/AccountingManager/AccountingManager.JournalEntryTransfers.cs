    public async Task<JournalEntry?> CreateJournalEntryFromTransferAsync(Transfer transfer, Guid currentUser)
        => (await CreateJournalEntryFromTransferWithResultAsync(transfer, currentUser)).JournalEntry;

    private async Task<AccountingJournalEntryResult> CreateJournalEntryFromTransferWithResultAsync(Transfer transfer, Guid currentUser)
    {
        var trail = new AccountingSyncBailTrail();
        var result = await CreateJournalEntryFromTransferWithDiagnosticsAsync(transfer, currentUser, trail);
        if (result.JournalEntry == null && !result.HasWarning)
            return AccountingJournalEntryResult.WarningResult(trail.FormatBailTrail());
        return result;
    }

    private async Task<AccountingJournalEntryResult> CreateJournalEntryFromTransferWithDiagnosticsAsync(
        Transfer transfer,
        Guid currentUser,
        AccountingSyncBailTrail trail)
    {
        var transferLabel = string.IsNullOrWhiteSpace(transfer.TransferCode)
            ? transfer.TransferId.ToString()
            : transfer.TransferCode.Trim();
        trail.Note($"Transfer {transferLabel} IsActive={transfer.IsActive} Amount={transfer.Amount:0.00} Splits={transfer.Splits?.Count ?? 0}");

        if (!await IsAccountingFeatureEnabledAsync(transfer.OrganizationId))
        {
            trail.Bail("Exit: accounting feature is disabled for organization.");
            return AccountingJournalEntryResult.WarningResult("Accounting feature is disabled for organization.");
        }

        if (!ShouldCreateJournalEntryForTransfer(transfer))
        {
            AppendTransferShouldCreateBailReasons(transfer, trail);
            trail.Bail("Exit: ShouldCreateJournalEntryForTransfer=false.");
            return AccountingJournalEntryResult.WarningResult(trail.FormatBailTrail());
        }

        try
        {
            ValidateTransferForJournalEntry(transfer);

            await EnrichTransferSplitsFromJournalEntryLinesAsync(transfer);
            ApplyTransferHeaderContextFromSplits(transfer);
            trail.Note($"After enrich: splits={transfer.Splits?.Count ?? 0}");

            var journalEntry = await BuildJournalEntryFromTransferRecordAsync(transfer, currentUser);
            trail.Note($"Built transfer JE lines={journalEntry.JournalEntryLines?.Count ?? 0}");

            var created = await CreateAutoGeneratedJournalEntryAsync(journalEntry);
            if (created == null)
            {
                trail.Bail("Exit: CreateAutoGeneratedJournalEntryAsync returned null (feature off or rejected).");
                return AccountingJournalEntryResult.WarningResult(trail.FormatBailTrail());
            }

            trail.Note($"Created {created.JournalEntryCode} kind={(int)created.JournalEntryKindId} TransferId={created.TransferId}");
            await SyncTransferDocumentLinksAsync(transfer, currentUser);
            trail.Note("SyncTransferDocumentLinksAsync completed.");

            return AccountingJournalEntryResult.Success(created);
        }
        catch (Exception ex)
        {
            trail.Bail($"Exception: {ex.Message}");
            await LogAccountingErrorAsync(
                trigger: "Transfer",
                organizationId: transfer.OrganizationId,
                officeId: transfer.OfficeId,
                sourceTypeId: (int)SourceType.Transfer,
                sourceId: transfer.TransferId,
                documentCode: transferLabel,
                accountingPeriod: transfer.AccountingPeriod == default ? null : transfer.AccountingPeriod,
                amount: transfer.Amount,
                message: ex.Message + Environment.NewLine + "Bail trail:" + Environment.NewLine + trail.FormatBailTrail(),
                currentUser: currentUser);
            return AccountingJournalEntryResult.WarningResult(ex.Message);
        }
    }

