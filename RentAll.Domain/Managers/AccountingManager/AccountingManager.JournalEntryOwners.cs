    private static bool ShouldCreateJournalEntryForWorkOrder(WorkOrder workOrder)
        => workOrder.WorkOrderType is WorkOrderType.Tenant or WorkOrderType.Owner or WorkOrderType.Company;

    private static bool ShouldCreateOwnerUtilityJournalEntryForBill(Receipt bill)
    {
        if (!bill.IsUtility)
            return false;

        var eligibleSplits = ResolveReceiptSplitLines(bill).Where(IsJournalEligibleReceiptSplit).ToList();
        if (eligibleSplits.Count == 0)
            return false;

        // Owner utility JE is created when any eligible split is Owner type; mixed split sets still
        // create owner utility entries for the owner portion only.
        return eligibleSplits.Any(split => split.ReceiptType == ReceiptType.Owner);
    }

    private async Task<decimal> GetProratedOwnerFlatAmountAsync(Invoice invoice, decimal flatAmount, LedgerLine rentalLine)
    {
        // The owner's flat (and minimum) amount is a full-month figure. Partial stays use the same
        // 30-day proration as rent (e.g. 3000 flat for 5 days → 500). Full calendar months
        // (Feb 28, Jul 31, etc.) and 30+ day stays use the full flat amount.
        if (flatAmount == 0)
            return 0m;

        var days = await GetRentalLedgerLineDaysAsync(invoice, rentalLine);
        if (days <= 0)
            return 0m;

        var daysInMonth = ResolveOwnerFlatProrateDaysInMonth(invoice, rentalLine);
        if (!(days < daysInMonth && days < PRORATE_DAYS))
            return flatAmount;

        return Math.Round(flatAmount / PRORATE_DAYS * days, 2, MidpointRounding.AwayFromZero);
    }

    private static int ResolveOwnerFlatProrateDaysInMonth(Invoice invoice, LedgerLine rentalLine)
    {
        if (invoice.AccountingPeriod != default)
            return DateTime.DaysInMonth(invoice.AccountingPeriod.Year, invoice.AccountingPeriod.Month);

        var referenceYear = invoice.InvoiceDate.Year;
        if (TryParseRentalFeeDateRange(rentalLine.Description, referenceYear, out var rentalStart, out _))
            return DateTime.DaysInMonth(rentalStart.Year, rentalStart.Month);

        return PRORATE_DAYS;
    }

    private async Task<int> GetRentalLedgerLineDaysAsync(Invoice invoice, LedgerLine rentalLine)
    {
        var referenceYear = invoice.AccountingPeriod != default
            ? invoice.AccountingPeriod.Year
            : invoice.InvoiceDate.Year;

        if (!TryParseRentalFeeDateRange(rentalLine.Description, referenceYear, out var rentalStart, out var rentalEnd))
            return 0;

        if (invoice.AccountingPeriod != default
            && !TryClipRentalRangeToAccountingPeriod(rentalStart, rentalEnd, invoice.AccountingPeriod, out rentalStart, out rentalEnd))
        {
            return 0;
        }

        var reservation = invoice.ReservationId.HasValue
            ? await _reservationRepository.GetReservationByIdAsync(invoice.ReservationId.Value, invoice.OrganizationId)
            : null;
        var billingType = reservation?.BillingType ?? BillingType.Monthly;
        var departureDate = reservation == null
            ? rentalEnd
            : ResolveBillingDepartureDate(reservation);

        return CalculateNumberOfDays(
            rentalStart,
            rentalEnd,
            billingType,
            IsDepartureMonthYear(rentalEnd, departureDate),
            IsLastDayOfMonth(rentalEnd));
    }

    private static bool TryClipRentalRangeToAccountingPeriod(DateOnly rentalStart, DateOnly rentalEnd, DateOnly accountingPeriod, out DateOnly clippedStart, out DateOnly clippedEnd)
    {
        clippedStart = rentalStart;
        clippedEnd = rentalEnd;

        if (accountingPeriod == default)
            return clippedEnd >= clippedStart;

        var periodMonthStart = FirstDayOfMonth(accountingPeriod);
        var periodMonthEnd = LastDayOfMonth(accountingPeriod);

        if (rentalEnd < periodMonthStart || rentalStart > periodMonthEnd)
        {
            clippedStart = default;
            clippedEnd = default;
            return false;
        }

        if (clippedStart < periodMonthStart)
            clippedStart = periodMonthStart;

        if (clippedEnd > periodMonthEnd)
            clippedEnd = periodMonthEnd;

        return clippedEnd >= clippedStart;
    }

    private async Task<Guid?> ResolveWorkOrderOwnerContactIdAsync(WorkOrder workOrder)
    {
        if (!workOrder.PropertyId.HasValue || workOrder.PropertyId.Value == Guid.Empty)
            return null;

        var property = await _propertyRepository.GetPropertyByIdAsync(workOrder.PropertyId.Value, workOrder.OrganizationId);
        if (property?.Owner1Id is { } ownerId && ownerId != Guid.Empty)
            return ownerId;

        return null;
    }

    private static List<WorkOrderItem> GetEligibleWorkOrderOwnerLines(WorkOrder workOrder)
    {
        var workOrderLines = (workOrder.WorkOrderItems ?? new List<WorkOrderItem>())
            .Where(item => item.ItemAmount != 0).OrderBy(item => item.WorkOrderItemId).ToList();
        if (workOrderLines.Count > 0)
            return workOrderLines;

        if (workOrder.Amount == 0)
            return new List<WorkOrderItem>();

        return
        [
            new WorkOrderItem
            {
                Description = workOrder.Description,
                ItemAmount = workOrder.Amount
            }
        ];
    }

    private async Task<decimal?> CalculateOwnerShareAmountForInvoiceAsync(Invoice invoice, decimal amount)
    {
        var propertyId = await ResolveInvoicePropertyIdAsync(invoice);
        if (propertyId == null || propertyId == Guid.Empty)
            return null;

        var property = await _propertyRepository.GetPropertyByIdAsync(propertyId.Value, invoice.OrganizationId);
        var propertyAgreement = await _propertyRepository.GetPropertyAgreementByPropertyIdAsync(propertyId.Value);
        if (property == null || propertyAgreement == null)
            return null;

        if (property.PropertyLeaseType != PropertyLeaseType.PropertyManagement)
            return null;

        if (!TryGetInvoiceRentalLedgerLine(invoice, out var rentalLine))
            return null;

        decimal ownerAmount = 0m;
        switch (propertyAgreement.ManagementFeeType)
        {
            case ManagementFeeType.FlatRate:
                ownerAmount = await GetProratedOwnerFlatAmountAsync(invoice, propertyAgreement.FlatRateAmount, rentalLine);
                break;

            case ManagementFeeType.Percentage:
                ownerAmount = amount * propertyAgreement.RevenueSplitOwner / 100m;
                break;

            case ManagementFeeType.Minimum:
                {
                    ownerAmount = amount * propertyAgreement.RevenueSplitOwner / 100m;
                    var proratedMinimum = await GetProratedOwnerFlatAmountAsync(invoice, propertyAgreement.FlatRateAmount, rentalLine);
                    if (ownerAmount < proratedMinimum)
                        ownerAmount = proratedMinimum;
                    break;
                }
        }

        return ownerAmount;
    }
