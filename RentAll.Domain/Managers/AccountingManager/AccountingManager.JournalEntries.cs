    {
        await _journalEntryRepository.DeleteJournalEntriesBySourceIdAsync(invoice.OrganizationId, (int)SourceType.Invoice, invoice.InvoiceId);
        await DeleteJournalEntriesForSourceAsync(
            invoice.OrganizationId,
            invoice.OfficeId,
            (int)SourceType.OwnerDistribution,
            invoice.InvoiceId);
    }

    private async Task DeleteJournalEntriesForReceiptAsync(Receipt receipt)
    {
        await _journalEntryRepository.DeleteJournalEntriesBySourceIdAsync(receipt.OrganizationId, (int)SourceType.Receipt, receipt.ReceiptId);
        await DeleteAllCrossOfficeReceiptCompanionEntriesAsync(receipt);
    }

    private async Task DeleteJournalEntriesForBillAsync(Receipt bill)
    {
        if (bill.ReceiptId == Guid.Empty)
            return;

        await _journalEntryRepository.DeleteJournalEntriesBySourceIdAsync(bill.OrganizationId, (int)SourceType.Bill, bill.ReceiptId);
        await _journalEntryRepository.DeleteJournalEntriesBySourceIdAsync(bill.OrganizationId, (int)SourceType.BillPayment, bill.ReceiptId);

        var sourceCodes = ResolveBillJournalEntrySourceCodeCandidates(bill).ToList();
        if (sourceCodes.Count == 0)
            return;

        await _journalEntryRepository.DeleteOpenJournalEntriesBySourceCodesAsync(
            bill.OrganizationId,
            bill.OfficeId,
            [(int)SourceType.Bill, (int)SourceType.BillPayment],
            sourceCodes);
    }

    private async Task DeleteJournalEntriesForWorkOrderAsync(WorkOrder workOrder)
    {
        if (workOrder.WorkOrderId == Guid.Empty)
            return;

        await DeleteJournalEntriesForSourceAsync(
            workOrder.OrganizationId,
            workOrder.OfficeId,
            (int)SourceType.WorkOrder,
            workOrder.WorkOrderId);
    }

    private async Task DeleteJournalEntriesForPaymentAsync(Payment payment)
    {
        if (payment.PaymentId == Guid.Empty)
            return;

        var linkedEntries = await GetJournalEntriesByPaymentIdCachedAsync(payment.OrganizationId, payment.PaymentId);
        foreach (var entry in linkedEntries)
            await DeleteOpenJournalEntryAsync(entry.JournalEntryId, payment.OrganizationId);

        var invoicePaymentEntries = await GetJournalEntriesForSourceAsync(
            payment.OrganizationId,
            payment.OfficeId,
            SourceType.InvoicePayment,
            payment.PaymentId);

        foreach (var entry in invoicePaymentEntries)
            await DeleteOpenJournalEntryAsync(entry.JournalEntryId, payment.OrganizationId);

        var billPaymentEntries = await GetJournalEntriesForSourceAsync(
            payment.OrganizationId,
            payment.OfficeId,
            SourceType.BillPayment,
            payment.PaymentId);

        foreach (var entry in billPaymentEntries)
            await DeleteOpenJournalEntryAsync(entry.JournalEntryId, payment.OrganizationId);
    }

    public async Task<JournalEntry> UnpostJournalEntryAsync(Guid journalEntryId, Guid organizationId, Guid currentUser)
    {
        var journalEntry = await _journalEntryRepository.GetJournalEntryByIdAsync(journalEntryId, organizationId);
        if (journalEntry == null)
            throw new Exception("Journal entry not found");

        if (journalEntry.PostingStatusId is PostingStatus.SoftClosed or PostingStatus.HardClosed)
            throw new Exception("A voided journal entry cannot be unposted");

        if (journalEntry.PostingStatusId != PostingStatus.Posted)
            throw new Exception("Journal entry is not posted");

        journalEntry.PostingStatusId = PostingStatus.Open;
        journalEntry.ModifiedBy = currentUser;
        return await _journalEntryRepository.UpdateJournalEntryByIdAsync(journalEntry);
    }

    private static bool HasActiveJournalEntryLines(JournalEntry journalEntry)
        => journalEntry.JournalEntryLines.Any(l => l.Debit != 0 || l.Credit != 0);

    private static bool HasInvalidActiveJournalEntryAccountIds(JournalEntry journalEntry)
        => journalEntry.JournalEntryLines.Any(l => (l.Debit != 0 || l.Credit != 0) && l.ChartOfAccountId <= 0);

    private static void ValidateJournalEntryForSave(JournalEntry journalEntry, bool requireActiveLines)
    {
        if (journalEntry.OfficeId <= 0)
            throw new Exception("OfficeId is required");

        if (journalEntry.TransactionDate == default)
            throw new Exception("TransactionDate is required");

        if (journalEntry.AccountingPeriod == default)
            throw new Exception("AccountingPeriod is required");

        var activeLines = journalEntry.JournalEntryLines
            .Where(l => l.Debit != 0 || l.Credit != 0)
            .ToList();

        if (requireActiveLines && activeLines.Count == 0)
            throw new Exception("At least one journal entry line is required");

        foreach (var line in activeLines)
        {
            if (line.ChartOfAccountId <= 0)
                throw new Exception("ChartOfAccountId is required on each journal entry line");

            if (line.Debit < 0 || line.Credit < 0)
                throw new Exception("Debit and Credit must be zero or greater");

            if (line.Debit != 0 && line.Credit != 0)
                throw new Exception("A journal entry line cannot have both debit and credit amounts");
        }

        var totalDebit = activeLines.Sum(l => l.Debit);
        var totalCredit = activeLines.Sum(l => l.Credit);

        if (Math.Abs(totalDebit - totalCredit) > 0.005m)
            throw new Exception("Journal entry debits and credits must balance");
    }

    private static bool IsUserEditableJournalEntry(JournalEntry journalEntry)
        => journalEntry.SourceTypeId == (int)SourceType.Journal
            && journalEntry.JournalEntryKindId is JournalEntryKind.Manual
                or JournalEntryKind.OpeningBalanceSheet
                or JournalEntryKind.RetainedEarnings;

    private static bool IsDeletableJournalEntry(JournalEntry journalEntry)
        => journalEntry.PostingStatusId is PostingStatus.Open
            or PostingStatus.Posted
            or PostingStatus.SoftClosed;

    private static void PreserveJournalEntryDocumentLinksUnlessSet(JournalEntry journalEntry, JournalEntry existing)
    {
        if (journalEntry.PaymentId is null || journalEntry.PaymentId == Guid.Empty)
            journalEntry.PaymentId = existing.PaymentId;
        if (string.IsNullOrWhiteSpace(journalEntry.PaymentCode))
            journalEntry.PaymentCode = existing.PaymentCode;

        if (journalEntry.DepositId is null || journalEntry.DepositId == Guid.Empty)
            journalEntry.DepositId = existing.DepositId;
        if (string.IsNullOrWhiteSpace(journalEntry.DepositCode))
            journalEntry.DepositCode = existing.DepositCode;

        if (journalEntry.TransferId is null || journalEntry.TransferId == Guid.Empty)
            journalEntry.TransferId = existing.TransferId;
        if (string.IsNullOrWhiteSpace(journalEntry.TransferCode))
            journalEntry.TransferCode = existing.TransferCode;
    }
